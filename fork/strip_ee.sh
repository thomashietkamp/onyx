#!/usr/bin/env bash
# Remove all Enterprise Edition (EE) code from this fork, so that only
# MIT-licensed code is left. Run it from the repo root after every merge of
# upstream main. It is idempotent: a second run changes nothing.
#
# It removes:
#   - the EE source trees (backend/ee, web/src/ee, web/src/app/ee),
#     and leaves an empty backend/ee package, as the upstream onyx-foss
#     mirror does (backend/scripts/make_foss_repo.sh);
#   - backend tests and scripts that import or patch EE modules, because
#     they cannot run without the EE code.
#
# A modify/delete merge conflict on one of these paths is resolved by the
# removal, because `git rm` stages the deletion.
set -euo pipefail

EXTRA_EE_PATHS=(
  backend/tests/unit/scripts/test_seed_dev_license_cache.py
  backend/tests/integration/tests/migrations/test_run_multitenant_migrations.py
  # Re-exports an EE page.
  web/src/app/admin/hooks/page.tsx
)

# Test helpers that exist only for EE features. Each one is removed with
# every test module that imports it.
EE_ONLY_HELPERS=(
  backend/tests/daily/connectors/confluence/models.py
  backend/tests/integration/common_utils/document_acl.py
  backend/tests/integration/common_utils/managers/document_search.py
  backend/tests/integration/common_utils/managers/query_history.py
  backend/tests/integration/common_utils/managers/spending_limits.py
  backend/tests/regression/search_quality/run_search_eval.py
)

repo_root="$(git rev-parse --show-toplevel)"
cd "$repo_root"

remove_path() {
  local path="$1"
  if git ls-files --error-unmatch -- "$path" >/dev/null 2>&1 \
    || git ls-files -u -- "$path" | grep -q .; then
    git rm -r -q --force -- "$path"
  fi
  rm -rf -- "$path"
}

echo "=== Removing EE source trees ==="
for tree in backend/ee web/src/ee web/src/app/ee; do
  remove_path "$tree"
done

mkdir -p backend/ee
: > backend/ee/__init__.py
git add backend/ee/__init__.py

echo "=== Removing EE test directories ==="
while IFS= read -r dir; do
  remove_path "$dir"
done < <(find backend/tests -type d -name ee -not -path "*/__pycache__/*" | sort)

echo "=== Removing backend tests and scripts that depend on EE ==="
# A file depends on EE when it imports `ee` or names an `ee.onyx` module in
# a string (mock.patch targets, importlib lookups). Only test modules and
# scripts are removed. Helpers and conftest.py files also serve MIT tests,
# so the check below reports them instead.
ee_pattern='^\s*(from|import) ee(\.|\s|$)|["'"'"']ee\.onyx'
while IFS= read -r file; do
  remove_path "$file"
done < <(
  {
    grep -rlE "$ee_pattern" --include='test_*.py' backend/tests 2>/dev/null || true
    grep -rlE "$ee_pattern" --include=*.py backend/scripts backend/alembic \
      2>/dev/null || true
  } | sort
)

# Paths that need EE code without naming it (tests of removed scripts).
for path in "${EXTRA_EE_PATHS[@]}"; do
  remove_path "$path"
done

for helper in "${EE_ONLY_HELPERS[@]}"; do
  module="${helper#backend/}"
  module="${module%.py}"
  module="${module//\//.}"
  while IFS= read -r file; do
    remove_path "$file"
  done < <(grep -rlF "$module" --include='test_*.py' backend/tests 2>/dev/null || true)
  remove_path "$helper"
done

echo "=== Removing web tests that depend on EE ==="
web_import_pattern="from [\"'](@/ee/|@/app/ee/)"
while IFS= read -r file; do
  remove_path "$file"
done < <(grep -rlE "$web_import_pattern" --include='*.test.ts' \
  --include='*.test.tsx' web/src web/tests 2>/dev/null | sort || true)

echo "=== Checking for EE references left in MIT code ==="
# Every file under backend/tests that is not a test module is a helper.
# MIT runtime code may name ee modules in strings (the edition dispatcher,
# optional celery task lists), so only an import is an error there.
import_pattern='^\s*(from|import) ee(\.|\s|$)'
left="$(
  {
    grep -rlE "$import_pattern" --include=*.py backend \
      --exclude-dir=ee --exclude-dir=.venv 2>/dev/null || true
    grep -rlE "$ee_pattern" --include=*.py --exclude='test_*.py' backend/tests \
      2>/dev/null || true
  } | sort -u
)"
web_left="$(grep -rlE "$web_import_pattern" web/src web/tests 2>/dev/null || true)"
if [[ -n "$left$web_left" ]]; then
  echo "These MIT files still reference EE code. Fix them by hand:"
  printf '%s\n' "$left" "$web_left" | sed '/^$/d'
  exit 1
fi

echo "=== Listing feature map paths that only EE code had ==="
# Upstream keeps the map valid with EE present, so every path it cites that
# is missing now was removed above. check_feature_map.py skips this list.
removed_list=.agents/feature-map/fork-removed-paths.txt
: > "$removed_list"
{
  echo "# Generated by fork/strip_ee.sh. Do not edit."
  echo "# Feature map paths that only the removed EE code had."
  # shellcheck disable=SC2016 # the backticks are literal, not an expansion
  python3 .agents/feature-map/check_feature_map.py 2>&1 \
    | grep "does not exist in the repo" \
    | grep -oE '`[^`]+`' | tr -d '`' | sort -u || true
} > "$removed_list.tmp"
mv "$removed_list.tmp" "$removed_list"
git add "$removed_list"
python3 .agents/feature-map/check_feature_map.py

echo "=== Done: no EE code left ==="
